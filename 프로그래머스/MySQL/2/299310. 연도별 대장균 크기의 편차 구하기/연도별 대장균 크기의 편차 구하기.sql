SELECT 
    YEAR(DIFFERENTIATION_DATE) AS YEAR,
    (MAX_TABLE.max_size - E.SIZE_OF_COLONY) AS YEAR_DEV,
    E.ID
FROM 
    ECOLI_DATA E
JOIN 
    (
        SELECT 
            YEAR(DIFFERENTIATION_DATE) AS yr, 
            MAX(SIZE_OF_COLONY) AS max_size
        FROM ECOLI_DATA
        GROUP BY YEAR(DIFFERENTIATION_DATE)
    ) MAX_TABLE 
ON 
    YEAR(E.DIFFERENTIATION_DATE) = MAX_TABLE.yr
ORDER BY 
    YEAR ASC, YEAR_DEV ASC;
