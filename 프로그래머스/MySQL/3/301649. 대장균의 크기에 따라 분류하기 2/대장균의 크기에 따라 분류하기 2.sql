SELECT ID,
       CASE
           WHEN RANK_NUM = 1 THEN 'CRITICAL'
           WHEN RANK_NUM = 2 THEN 'HIGH'
           WHEN RANK_NUM = 3 THEN 'MEDIUM'
           WHEN RANK_NUM = 4 THEN 'LOW'
       END AS COLONY_NAME
FROM (
    SELECT ID,
           NTILE(4) OVER (ORDER BY SIZE_OF_COLONY DESC) AS RANK_NUM
    FROM ECOLI_DATA
) AS T
ORDER BY ID ASC;
